/**
 * Allocate payments to directed bills or to the oldest outstanding bills.
 * Principal is settled before penalty within each bill.
 * Conserves money: applied amounts plus unapplied balance equal the payment.
 */
import { compareBillPeriod, outstandingAmount } from '@/lib/utils/billing';

/**
 * Named so a second rule (interest-first, or proportional across equal-dated
 * debts under s.61's second limb) becomes a new branch and a new test rather
 * than a rewrite of every caller.
 */
export type AppropriationPolicy = 'oldest-first-principal-before-penalty';

export const DEFAULT_APPROPRIATION_POLICY: AppropriationPolicy = 'oldest-first-principal-before-penalty';

export type AppropriableBill = {
  id: string;
  bill_period_year: number;
  bill_period_month: number;
  /** Generated by the database — never recomputed here. */
  payable_amount: number;
  /** Already settled by earlier payments or advance settlements. */
  amount_settled: number;
  /** The penalty portion inside payable_amount, if any. */
  penalty_amount: number;
};

export type BillAllocation = {
  bill_id: string;
  /** Total applied to this bill. */
  applied: number;
  /** Portion of `applied` that went to principal rather than penalty. */
  applied_to_principal: number;
  /** Portion of `applied` that went to the penalty. */
  applied_to_penalty: number;
  /** True when this allocation brings amount_settled up to payable_amount. */
  settles_bill: boolean;
};

export type Allocation = {
  perBill: BillAllocation[];
  /** Money left over once every eligible bill is covered — an advance. */
  unapplied: number;
};

/** Paise, not rupees: money is compared at 2dp, never with float equality. */
const EPSILON = 0.005;

function round2(value: number): number {
  return Math.round(value * 100) / 100;
}

/**
 * What is still owed on a bill. Re-exported from the billing module rather than
 * recomputed, so this module, the dues notice and the dues totals cannot drift
 * apart on what "outstanding" means.
 */
export const outstandingOn: (bill: AppropriableBill) => number = outstandingAmount;

function applyToBill(bill: AppropriableBill, available: number): BillAllocation | null {
  const outstanding = outstandingOn(bill);
  if (outstanding <= EPSILON || available <= EPSILON) return null;

  const applied = round2(Math.min(outstanding, available));

  // Principal before penalty. The penalty portion still outstanding is whatever
  // part of penalty_amount this bill has not yet had settled; principal is the
  // rest. Consuming principal first means a part-payment reduces the balance the
  // bye-laws care about before it touches the interest component.
  const penaltyOutstanding = Math.max(0, Math.min(Number(bill.penalty_amount), outstanding));
  const principalOutstanding = round2(outstanding - penaltyOutstanding);
  const appliedToPrincipal = round2(Math.min(applied, principalOutstanding));
  const appliedToPenalty = round2(applied - appliedToPrincipal);

  return {
    bill_id: bill.id,
    applied,
    applied_to_principal: appliedToPrincipal,
    applied_to_penalty: appliedToPenalty,
    settles_bill: applied >= outstanding - EPSILON,
  };
}

/**
 * s.61 default: no direction given, so discharge in order of time.
 *
 * Greedy over an already-ordered list — O(n log n) for the sort, O(n) for the
 * scan, where n is months of arrears. `compareBillPeriod` is shared with the
 * dues notice so the two can never disagree about which month is oldest.
 */
export function allocate(
  bills: AppropriableBill[],
  amount: number,
  policy: AppropriationPolicy = DEFAULT_APPROPRIATION_POLICY,
): Allocation {
  if (policy !== DEFAULT_APPROPRIATION_POLICY) {
    throw new Error(`Unsupported appropriation policy: ${policy}`);
  }

  let remaining = round2(Math.max(0, amount));
  const perBill: BillAllocation[] = [];

  for (const bill of [...bills].sort(compareBillPeriod)) {
    const allocation = applyToBill(bill, remaining);
    if (!allocation) continue;
    perBill.push(allocation);
    remaining = round2(remaining - allocation.applied);
    if (remaining <= EPSILON) break;
  }

  return { perBill, unapplied: Math.max(0, remaining) };
}

/**
 * s.59: the resident named the months, so honour exactly those and no others —
 * even when an older bill is outstanding. Anything left over after the chosen
 * bills are covered stays unapplied rather than silently spilling onto months
 * the payer did not choose.
 */
export function allocateDirected(
  bills: AppropriableBill[],
  billIds: string[],
  amount: number,
  policy: AppropriationPolicy = DEFAULT_APPROPRIATION_POLICY,
): Allocation {
  const directed = new Set(billIds);
  return allocate(bills.filter(bill => directed.has(bill.id)), amount, policy);
}

/** Total actually applied across a result — the complement of `unapplied`. */
export function totalApplied(allocation: Allocation): number {
  return round2(allocation.perBill.reduce((sum, bill) => sum + bill.applied, 0));
}
