import { readFile, readdir, stat } from 'node:fs/promises';
import path from 'node:path';

const publicStaticRoot = path.resolve('.next', 'static');

async function filesUnder(directory) {
  // The recursion starts at the fixed local .next/static root above; directory
  // values come only from entries returned beneath that root, never user input.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  const entries = await readdir(directory, { withFileTypes: true });
  return (await Promise.all(entries.map(entry => {
    const target = path.join(directory, entry.name);
    return entry.isDirectory() ? filesUnder(target) : [target];
  }))).flat();
}

const files = await filesUnder(publicStaticRoot);
const publicMaps = files.filter(file => file.endsWith('.map'));
const mappedScripts = [];

for (const file of files.filter(candidate => candidate.endsWith('.js'))) {
  // `file` is one of the paths discovered beneath the fixed .next/static root.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  const contents = await readFile(file, 'utf8');
  if (/\bsourceMappingURL\s*=/.test(contents)) mappedScripts.push(file);
}

if (publicMaps.length > 0 || mappedScripts.length > 0) {
  console.error('Production build exposes browser source-map artifacts.');
  for (const file of [...publicMaps, ...mappedScripts]) console.error(path.relative('.', file));
  process.exit(1);
}

console.log(`Production artifact check passed: ${files.length} public static files, no browser source maps.`);

// ── Self-hosted OCR engine assets ───────────────────────────────────────────
// public/tesseract/ is generated by scripts/copy-ocr-assets.mjs (run from both
// `prepare` and `prebuild`) and is gitignored, so a deploy that skipped npm
// lifecycle scripts, or a library upgrade that moved a source path, ships a
// build with no recognition engine. That failure is silent by design:
// extractPaymentFields swallows every error, so the resident sees a progress
// bar and then an unchanged form, and nothing is logged.
//
// The copy script already fails when a SOURCE path disappears. This checks the
// other end — that the files a browser will actually request are present in the
// deployable tree, under the exact names tesseract.js builds at runtime:
//
//   worker  new Worker(workerPath)                         (spawnWorker.js)
//   core    `${corePath}/tesseract-core-<variant>.wasm.js`  (getCore.js)
//   lang    `${langPath}/${lang}.traineddata.gz`            (worker-script/index.js)
//
// All three core variants are required: getCore picks one per device at runtime
// by detecting relaxed-SIMD, then SIMD, then neither. Both path helpers strip a
// trailing slash and rejoin with '/', which is why the '/tesseract/core' and
// '/tesseract/lang' values in src/lib/payments/ocr.ts carry no trailing slash.
const ocrAssets = [
  ['public/tesseract/worker.min.js', 50_000],
  ['public/tesseract/core/tesseract-core-relaxedsimd-lstm.wasm.js', 1_000_000],
  ['public/tesseract/core/tesseract-core-simd-lstm.wasm.js', 1_000_000],
  ['public/tesseract/core/tesseract-core-lstm.wasm.js', 1_000_000],
  ['public/tesseract/lang/eng.traineddata.gz', 1_000_000],
];

const ocrProblems = [];
for (const [relativePath, minBytes] of ocrAssets) {
  // Fixed, hardcoded repository paths — never user input or argv.
  // eslint-disable-next-line security/detect-non-literal-fs-filename
  const stats = await stat(path.resolve(relativePath)).catch(() => null);
  if (stats === null) {
    ocrProblems.push(`${relativePath} is missing`);
  } else if (stats.size < minBytes) {
    ocrProblems.push(`${relativePath} is ${stats.size} bytes, expected at least ${minBytes}`);
  }
}

if (ocrProblems.length > 0) {
  console.error('Self-hosted OCR engine assets are not deployable:');
  for (const problem of ocrProblems) console.error(`  ${problem}`);
  console.error(
    '\nRun `node scripts/copy-ocr-assets.mjs`. If it reports missing SOURCE files, a '
      + 'tesseract.js / tesseract.js-core / @tesseract.js-data/eng upgrade moved them: update '
      + 'the manifest in that script, re-verify recognition against a production build, and '
      + 'update the expected names here to match.'
  );
  process.exit(1);
}

console.log(`OCR asset check passed: ${ocrAssets.length} self-hosted engine files present.`);
